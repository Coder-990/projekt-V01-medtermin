DROP TABLE IF EXISTS rezervacije;
DROP TABLE IF EXISTS nalazi;
DROP TABLE IF EXISTS termini;
DROP TABLE IF EXISTS lijecnici;
DROP TABLE IF EXISTS postavke;
DROP TABLE IF EXISTS reset_tokeni;
DROP TABLE IF EXISTS korisnici;

CREATE TABLE korisnici (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(50)  NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    email         VARCHAR(120),
    ime           VARCHAR(60),
    prezime       VARCHAR(60),
    uloga         VARCHAR(20)  NOT NULL,
    oib           VARCHAR(11)
);

CREATE TABLE reset_tokeni (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username   VARCHAR(50)  NOT NULL,
    token      VARCHAR(128) NOT NULL,
    istjece    TIMESTAMP,
    iskoristen BOOLEAN      DEFAULT FALSE NOT NULL
);

CREATE TABLE postavke (
    username   VARCHAR(50) PRIMARY KEY,
    podsjetnik BOOLEAN     NOT NULL,
    sati_prije INT         NOT NULL,
    kanal      VARCHAR(20) NOT NULL
);

CREATE TABLE lijecnici (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ime             VARCHAR(60)  NOT NULL,
    prezime         VARCHAR(60)  NOT NULL,
    specijalizacija VARCHAR(100) NOT NULL,
    ordinacija      VARCHAR(60)  NOT NULL
);

CREATE TABLE termini (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lijecnik_id BIGINT    NOT NULL REFERENCES lijecnici (id),
    pocetak     TIMESTAMP NOT NULL,
    kapacitet   INT       NOT NULL,
    zauzeto     INT       DEFAULT 0 NOT NULL,
    napomena    VARCHAR(500)
);

CREATE TABLE rezervacije (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    termin_id  BIGINT      NOT NULL REFERENCES termini (id),
    pacijent   VARCHAR(50) NOT NULL,
    napomena   VARCHAR(1000),
    oib        VARCHAR(11),
    kreirano   TIMESTAMP   NOT NULL,
    oznaka_bis VARCHAR(40)
);

CREATE TABLE nalazi (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pacijent VARCHAR(50)  NOT NULL,
    naziv    VARCHAR(120) NOT NULL,
    datoteka VARCHAR(200) NOT NULL
);
